export function buildDemoDiaryEntries(state: GameState): DiaryEntry[] {
  const entries: DiaryEntry[] = [];

  // Entry 1 — Morning & Jukebox (unlocked after Movement 2)
  if (state.flags.demo_done_jukebox) {
    const jukeboxLines = state.flags.demo_jukebox_disobeyed
      ? [
          'Сильвер приклеил на автомат бумажку «Не включай». Ну я и не включала — я просто сначала открыла крышку, чтобы посмотреть, почему он хрипит!',
          'Внутри застрял самый странный болт на свете — блестящий, латунный, а резьба крутится не в ту сторону. Я его вытащила и забрала себе. А потом иголка сама прыгнула на пластинку, и автомат заиграл нашу старую песенку.',
          'Сильвер кричал из-за занавески, но Маленький Джон смешно наклонил голову, как огромная железная собака, так что было совсем не страшно.'
        ]
      : [
          'Сильвер написал на автомате «Не включай», и я честно не трогала ручку! Только протёрла стекло рукавом и заглянула сбоку через щель.',
          'Потом Сильвер сам нёс ящик, задел угол автомата — из-под крышки выкатился странный латунный болт с обратной резьбой, а пластинка вдруг зашипела и заиграла сама. Я тут же сказала: «Это не я!» Сильвер только фыркнул.',
          'Болт я оставила себе. Он красивый и тёплый, если долго держать его в кулаке.'
        ];

    entries.push({
      id: 'demo_diary_morning',
      day: state.day,
      weekday: 'Утро',
      title: 'Неправильный болт и старая пластинка',
      jillText: jukeboxLines,
      sketchLabel: 'Тот самый болт с резьбой наоборот!',
      photoArt: 'jill_john_bond',
      unlockedAt: 1,
    });
  }

  // Entry 2 — Salli, Fish & Gus (unlocked after Movement 4)
  if (state.flags.demo_done_gus) {
    let gusParagraph = '';
    if (state.flags.demo_gus_paid_own) {
      gusParagraph =
        'Днём приходил Гусь. Ему не хватило трёх гаек за суп, и он делал ужасно важное лицо, будто просто забыл кошелёк дома. Я тихонько доложила три свои гайки из тряпочки. Маслёнка для Джона подождёт, а суп был правда вкусный.';
    } else if (state.flags.demo_gus_tab_silver) {
      gusParagraph =
        'У Гуся не хватило трёх гаек за суп, так что я, пока Сильвер отвернулся к котлу, записала их в его тетрадку. Кажется, я перевернула букву «Г» в другую сторону — надеюсь, Сильвер подумает, что это его собственные каракули!';
    } else {
      gusParagraph =
        'У Гуся не хватало трёх гаек за суп. Я нарочно скривилась на весь зал, крикнула, что суп скис, и быстро унесла пустую миску на кухню. Гусь сначала вытаращил глаза, а потом еле сдержал смех. Суп на самом деле был отличный, я сама доела ложку на кухне!';
    }

    entries.push({
      id: 'demo_diary_midday',
      day: state.day,
      weekday: 'Полдень',
      title: 'Скользкая рыба и миска супа',
      jillText: [
        'Салли притащила целую корзину холодных рыб с большими глазами. Маленький Джон хотел помочь занести ящик, но его здоровенные медные плечи опять чуть не застряли в дверном косяке — пришлось смазать ему локоть и уговорить пройти боком.',
        'Салли рассказывала что-то про какого-то важного дядьку на верхних причалах с золотой монетой и чистыми сапогами. Взрослые вечно обсуждают чужие сапоги, а вот рыба правда смешно светилась, если зайти в тень.',
        gusParagraph,
      ],
      sketchLabel: 'Рыба с причала (ужасно скользкая)',
      photoArt: 'bar_admiral',
      unlockedAt: 2,
    });
  }

  // Entry 3 — Parents' Chest & Cold Wet Sleeves (unlocked after Movement 6)
  if (state.flags.demo_done_bulkhead) {
    entries.push({
      id: 'demo_diary_afternoon',
      day: state.day,
      weekday: 'После обеда',
      title: 'Радужная линза и мокрые рукава',
      jillText: [
        'Под лестницей я нашла старый сундук — Сильвер сказал, там вещи мамы и папы. Я нашла тяжёлую медную пряжку и стеклянную линзу! Если смотреть через неё на лампу, всё вокруг делается разноцветным.',
        'Там ещё была большая пожелтевшая бумага с линиями, но Сильвер сразу её забрал, ничего не объяснил и налил мне сладкой воды. Сладкая вода мне нравится, но иногда ужасно обидно, когда от меня прячут интересные картинки.',
        'Потом за бочками потекло из щели в стене. Вода была ледяная, я промочила оба рукава по локоть, зато пролезла туда, куда ни Сильвер, ни двухметровый Джон влезть не смогли, и затянула хомут сама! Руки до сих пор пахнут ржавчиной.'
      ],
      sketchLabel: 'Подсобка за бочками (очень холодно!)',
      photoArt: 'storeroom',
      unlockedAt: 3,
    });
  }

  // Entry 4 — Evening & Night Closing (unlocked at Movement 8)
  if (state.flags.demo_done_night) {
    const eveningDetail = state.flags.demo_gus_paid_own
      ? 'Вечером прибежал Гусь и молча положил мне на стойку гладкий зелёный камешек, обточенный водой. Он даже не сказал «спасибо», просто шмыгнул носом и убежал — значит, ему понравилось.'
      : state.flags.demo_gus_tab_silver
      ? 'Сильвер вечером долго разглядывал свою тетрадку и сказал, что у него внезапно испортился почерк, но не стал ругаться и просто зачеркнул три гайки. Всё-таки он добрый, хоть и ворчит.'
      : 'Вечером Сильвер попробовал свой суп, нахмурился и громко сказал на весь бар, что кое-кто слишком складно сочиняет сказки. А Салли мне подмигнула!';

    entries.push({
      id: 'demo_diary_night',
      day: state.day,
      weekday: 'Поздний вечер',
      title: 'Когда в «Адмирале» гасят лампы',
      jillText: [
        'Вечером народу набилось столько, что Маленькому Джону пришлось стоять в самом углу, чтобы никого не задеть железным локтем. Все шумели, смеялись и спорили о трубах.',
        eveningDetail,
        'Потом все разошлись, стулья подняли на столы, а пластинка в автомате играла уже совсем тихо и зацепилась на одном месте: шш-тук, шш-тук. Почему-то от неё вдруг стало немножко грустно, хотя день был хороший. Завтра надо будет снова проверить ту щель за бочками и дочистить линзу.'
      ],
      sketchLabel: 'Тихий «Адмирал» перед сном',
      photoArt: 'silver_smoking',
      unlockedAt: 4,
    });
  }

  // Fallback initial note if opened right at dawn
  if (entries.length === 0) {
    entries.push({
      id: 'demo_diary_dawn',
      day: state.day,
      weekday: 'Раннее утро',
      title: 'Совсем тихое утро',
      jillText: [
        'Я проснулась раньше всех — даже Сильвер ещё только гремит чайником на кухне, а Маленький Джон стоит у вешалки и тихонько гудит, как большой тёплый котёл.',
        'Надо протереть стойку, пока не пришли рыбаки. На музыкальном автомате приклеена какая-то жёлтая бумажка — интересно, что там написал Сильвер?'
      ],
      sketchLabel: 'Утро в «Адмирале»',
      photoArt: 'jill_john_bond',
      unlockedAt: 0,
    });
  }

  return entries;
}

